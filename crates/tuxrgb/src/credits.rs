pub fn rust_crates()
-> impl Iterator<Item = (&'static str, &'static str, &'static str, &'static str)> {
    RUST_CRATES
        .lines()
        .filter(|l| !l.starts_with('#'))
        .filter_map(|l| {
            let mut it = l.split('\t');
            Some((
                it.next()?,
                it.next()?,
                it.next().unwrap_or(""),
                it.next().unwrap_or(""),
            ))
        })
}
