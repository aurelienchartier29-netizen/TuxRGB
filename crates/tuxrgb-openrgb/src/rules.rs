//! udev rules generation.
//!
//! OpenRGB generates its `60-openrgb.rules` from the detectors compiled
//! into the binary (`openrgb --print-udev-rules`). TuxRGB asks the bundled
//! server for them so the rules always match the shipped hardware support;
//! a snapshot generated at build time is used as a fallback.

use std::path::Path;
use std::process::Command;
use std::time::Duration;

/// Generated from the bundled OpenRGB binary at build time
/// (`packaging/appimage/build-appimage.sh`). TuxRGB passes it straight to
/// pkexec: running `openrgb --print-udev-rules` takes ~9 s.
pub const BUNDLED_RULES: &str = include_str!("../../../data/udev/60-openrgb.rules");

/// File name expected by OpenRGB and the distributions.
pub const RULES_FILE_NAME: &str = "60-openrgb.rules";

/// Runs `openrgb --print-udev-rules` (unprivileged) with a timeout.
pub fn generate(binary: &Path) -> Result<String, String> {
    let mut child = Command::new(binary)
        .arg("--print-udev-rules")
        .env("QT_QPA_PLATFORM", "offscreen")
        .stdin(std::process::Stdio::null())
        .stdout(std::process::Stdio::piped())
        .stderr(std::process::Stdio::null())
        .spawn()
        .map_err(|e| format!("impossible de lancer OpenRGB : {e}"))?;
    let started = std::time::Instant::now();
    loop {
        match child.try_wait() {
            Ok(Some(_)) => break,
            Ok(None) if started.elapsed() > Duration::from_secs(15) => {
                let _ = child.kill();
                return Err("OpenRGB n'a pas répondu à temps".into());
            }
            Ok(None) => std::thread::sleep(Duration::from_millis(50)),
            Err(e) => return Err(e.to_string()),
        }
    }
    let out = child.wait_with_output().map_err(|e| e.to_string())?;
    let text = String::from_utf8_lossy(&out.stdout).into_owned();
    // Keep only the rules part (OpenRGB may print a banner first).
    let start = text
        .find("#---")
        .or_else(|| text.find("SUBSYSTEM"))
        .unwrap_or(0);
    let rules = text[start..].trim().to_owned();
    if rules
        .lines()
        .filter(|l| l.contains("TAG+=\"uaccess\""))
        .count()
        < 10
    {
        return Err("la sortie d'OpenRGB ne contient pas de règles udev".into());
    }
    Ok(rules + "\n")
}

/// Best available rules: generated by the bundled binary, else the snapshot.
pub fn best_rules(binary: Option<&Path>) -> String {
    binary
        .and_then(|b| generate(b).map_err(|e| tracing::warn!("{e}")).ok())
        .unwrap_or_else(|| BUNDLED_RULES.to_owned())
}

#[cfg(test)]
mod tests {
    #[test]
    fn bundled_snapshot_is_not_empty() {
        assert!(super::BUNDLED_RULES.contains("uaccess"));
    }
}
