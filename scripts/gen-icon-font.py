#!/usr/bin/env python3
"""Builds TuxRGB's icon fonts from Google's Material Symbols Rounded.

Material Symbols (Apache-2.0) is a 15 MB variable font. TuxRGB only needs
~100 glyphs, so this script:

  1. instances the variable font twice (outlined FILL=0 and filled FILL=1,
     wght=400, GRAD=0, opsz=24),
  2. subsets each instance to the code points listed in icons.txt,
  3. renames the families to "TuxRGB Symbols" / "TuxRGB Symbols Fill",
  4. writes crates/tuxrgb/src/ui/icons.rs with one constant per icon.

Usage (needs `pip install fonttools`):

    curl -LO "https://raw.githubusercontent.com/google/material-design-icons/master/variablefont/MaterialSymbolsRounded%5BFILL%2CGRAD%2Copsz%2Cwght%5D.ttf"
    curl -LO "https://raw.githubusercontent.com/google/material-design-icons/master/variablefont/MaterialSymbolsRounded%5BFILL%2CGRAD%2Copsz%2Cwght%5D.codepoints"
    python3 scripts/gen-icon-font.py <font.ttf> <font.codepoints>
"""

import pathlib
import sys

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

ROOT = pathlib.Path(__file__).resolve().parent.parent
ASSETS = ROOT / "crates/tuxrgb/assets/fonts"
ICONS_RS = ROOT / "crates/tuxrgb/src/ui/icons.rs"


def load_codepoints(path):
    table = {}
    for line in pathlib.Path(path).read_text().splitlines():
        parts = line.split()
        if len(parts) == 2:
            table.setdefault(parts[0], int(parts[1], 16))
    return table


def rename(font, family):
    for record in font["name"].names:
        if record.nameID in (1, 16):
            record.string = family
        elif record.nameID in (4,):
            record.string = family
        elif record.nameID == 6:
            record.string = family.replace(" ", "")
        elif record.nameID in (2, 17):
            record.string = "Regular"


def build(src, fill, family, out, unicodes):
    font = TTFont(src)
    font = instancer.instantiateVariableFont(
        font, {"FILL": fill, "wght": 400, "GRAD": 0, "opsz": 24}
    )
    options = subset.Options()
    options.layout_features = []
    options.name_IDs = ["*"]
    options.notdef_outline = True
    options.drop_tables += ["GSUB", "GPOS", "GDEF", "STAT"]
    sub = subset.Subsetter(options=options)
    sub.populate(unicodes=unicodes)
    sub.subset(font)
    rename(font, family)
    font.save(out)
    print(f"wrote {out} ({out.stat().st_size} bytes)")


def main():
    if len(sys.argv) != 3:
        print(__doc__)
        sys.exit(2)
    font_path, cp_path = sys.argv[1], sys.argv[2]
    table = load_codepoints(cp_path)
    names = [n.strip() for n in (ASSETS / "icons.txt").read_text().splitlines() if n.strip()]
    missing = [n for n in names if n not in table]
    if missing:
        sys.exit(f"unknown icons: {missing}")
    unicodes = sorted({table[n] for n in names})
    ASSETS.mkdir(parents=True, exist_ok=True)
    build(font_path, 0, "TuxRGB Symbols", ASSETS / "TuxRGBSymbols.ttf", unicodes)
    build(font_path, 1, "TuxRGB Symbols Fill", ASSETS / "TuxRGBSymbolsFill.ttf", unicodes)

    lines = [
        "// @generated by scripts/gen-icon-font.py – do not edit by hand.",
        "// Glyphs from Material Symbols Rounded (Apache-2.0, Google).",
        "#![allow(dead_code)]",
        "",
    ]
    for n in names:
        lines.append(f"pub const {n.upper()}: char = '\\u{{{table[n]:x}}}';")
    ICONS_RS.write_text("\n".join(lines) + "\n")
    print(f"wrote {ICONS_RS}")


if __name__ == "__main__":
    main()
